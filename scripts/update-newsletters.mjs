/**
 * Refresh js/data/newsletters.mjs from Foley Prep's public newsletter feed.
 *
 *   node scripts/update-newsletters.mjs
 *
 * foleyprep.com doesn't allow cross-origin reads, so the site can't fetch the feed in the
 * browser; instead this runs at deploy time (see .github/workflows/static.yml, which also
 * runs daily) and writes a fresh snapshot of the latest issues.
 */
import { writeFile } from "node:fs/promises";

const FEED = "https://foleyprep.com/newsletter/thumbnails";
const ARTICLE = "https://foleyprep.com/about/newsletters/";
const LATEST = 12;
const OUT = new URL("../js/data/newsletters.mjs", import.meta.url);

async function page(n) {
  const res = await fetch(`${FEED}?page=${n}`, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`${FEED}?page=${n} -> HTTP ${res.status}`);
  return res.json();
}

const first = await page(1);
const issues = [...first.results];
for (let n = 2; issues.length < LATEST && n <= first.totalPages; n++) {
  issues.push(...(await page(n)).results);
}
if (!issues.length) throw new Error("Newsletter feed returned no issues; keeping the existing snapshot.");

const latest = issues
  .sort((a, b) => b.date.localeCompare(a.date))
  .slice(0, LATEST)
  .map((i) => ({ title: i.title, date: i.date.slice(0, 10), thumbnail: i.thumbnail, url: ARTICLE + i.slug }));

const today = new Date().toISOString().slice(0, 10);
const file = `/**
 * Newsletters — the latest issues of the Foley Prep newsletter (the flagship company running on
 * Scorgi), pulled from ${FEED} on ${today}.
 * Generated by scripts/update-newsletters.mjs — don't edit by hand; re-run the script.
 */

export const NEWSLETTERS_TOTAL = ${first.total};

export const NEWSLETTERS_ARCHIVE_URL = "https://foleyprep.com/about/newsletters";

export const NEWSLETTERS = ${JSON.stringify(latest, null, 2)};
`;
await writeFile(OUT, file);
console.log(`Wrote ${latest.length} of ${first.total} issues (newest ${latest[0].date}) to js/data/newsletters.mjs`);
